"""Freeze a compact approximation of E1's calibration CDFs; no new fitting labels."""
from pathlib import Path
import json,numpy as np,zipfile
ROOT=Path(__file__).resolve().parents[3]
p=ROOT/'docs/diagnostics/assets/confidence-e1-2026-10-17'
arrays=[]
for case in ['avatar69','avatar300','anime1082']:
 with zipfile.ZipFile(p/case/'signals.zip') as z:
  for i in range(18):arrays.append(np.frombuffer(z.read(f'span2-pair{i}.f32'),dtype='<f4').reshape(-1,10))
a=np.concatenate(arrays);flat=[];offsets=[];errors=[]
for column in [0,1,2,3,4,5]:
 v=np.sort(a[:,column][np.isfinite(a[:,column])]);unique,counts=np.unique(v,return_counts=True)
 heavy=np.flatnonzero(counts>len(v)/2048)
 neighbors=np.unique(np.clip(np.concatenate([heavy-1,heavy,heavy+1]),0,len(unique)-1))
 knots=np.unique(np.concatenate([np.quantile(v,np.linspace(0,1,1025),method='nearest'),unique[neighbors]])).astype('f4')
 cdf=(np.searchsorted(v,knots,'left')+np.searchsorted(v,knots,'right'))/(2*len(v))
 offsets.append([len(flat)//2,len(knots)])
 flat.extend(x for pair in zip(knots,cdf) for x in pair)
 exact=(np.searchsorted(v,v,'left')+np.searchsorted(v,v,'right'))/(2*len(v));approx=np.interp(v,knots,cdf);errors.append(float(np.max(abs(exact-approx))))
print("CDF maximum errors:",errors)
assert max(errors)<.003
code='// Generated by E2Calibration.py from E1 calibration signals only.\nimport Foundation\nenum E2Calibration {\n'
code+='    static let spans: [SIMD2<UInt32>] = ['+','.join(f'SIMD2({o},{n})' for o,n in offsets)+']\n'
code+='    static let values: [Float] = [\n'+',\n'.join(','.join(f'{float(v):.9g}' if float(v)!=int(float(v)) else f'{int(float(v))}.0' for v in flat[i:i+12]) for i in range(0,len(flat),12))+'\n    ]\n}\n'
(ROOT/'Core/Interpolation/Swift/E2Calibration.swift').write_text(code)
out=ROOT/'docs/diagnostics/assets/confidence-e2-2026-10-17'
(out/'calibration.json').write_text(json.dumps({'source':'E1 train pairs0..17 only','uniformQuantiles':1025,'maxCDFAbsoluteErrorPerFeature':errors,'thresholdInitial':{'exit':.905458546512312,'enter':.9439189585770866,'full':.9583563380663478},'pixelUnitReference':[1152,480]},indent=2)+'\n')
print(errors)
